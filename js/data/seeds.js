export const packs = Object.entries(PACKS).map(([module, p]) => ({ module, label: p.label, ask: p.ask }));

export function packRows(module, hid, todayStr, pet) {
  const base = new Date(todayStr + 'T12:00');
  return PACKS[module].rows.map(([title, repeat, inDays, extra]) => {
    const d = new Date(base); d.setDate(d.getDate() + inDays);
    return { household_id: hid, module, done: false, due: d.toLocaleDateString('sv'),
      data: { title, repeat, ...extra, ...(pet && { pet }) } };
  });
}

